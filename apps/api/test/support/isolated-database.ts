import { execFile } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { PrismaClient } from '@prisma/client';

/**
 * Test database isolation: every integration run that needs tables gets its own throwaway PostgreSQL database,
 * created on the development server and dropped afterwards. Tests may create any tables they like in it, and can
 * never touch (or depend on) development or production data.
 *
 *   const db = await createIsolatedDatabase(adminDatabaseUrl());
 *   try { ...use db.url... } finally { await db.drop(); }
 *
 * Needs a role allowed to CREATE/DROP DATABASE: the Docker Compose superuser, passed as DATABASE_ADMIN_URL. That is test
 * tooling only: the API's own role (DATABASE_URL) cannot create databases, by design, and the application code under test never
 * connects with the admin URL. Never point this at production.
 *
 * For tests that exercise the real schema and privileges (`applyMigrations`, `urlFor`), the database is OWNED by the migration role
 * and the application connects as the API role, exactly like the Compose stack. No application-level test uses a superuser.
 */
export function adminDatabaseUrl(): string {
  const url = process.env.DATABASE_ADMIN_URL;
  if (!url)
    throw new Error(
      'DATABASE_ADMIN_URL is required for tests that create throwaway databases (run "pnpm setup:env").',
    );
  return url;
}

export type DatabaseRole = 'admin' | 'migrate' | 'api';

export interface IsolatedDatabase {
  readonly name: string;
  /** Connection string of the superuser to this database. For test tooling only (not for the application under test). */
  readonly url: string;
  /** Connection string of a role to THIS database: `migrate` owns the schema, `api` is what the application connects as. */
  urlFor(role: DatabaseRole): string;
  /** Applies the committed Prisma migrations as the migration role, like `prisma migrate deploy` in the Compose stack. */
  applyMigrations(): Promise<void>;
  drop(): Promise<void>;
}

const ROLE_ENV: Record<Exclude<DatabaseRole, 'admin'>, string> = {
  migrate: 'DATABASE_MIGRATE_URL',
  api: 'DATABASE_URL',
};

function withDatabase(url: string, name: string): string {
  const parsed = new URL(url);
  parsed.pathname = `/${name}`;
  return parsed.toString();
}

export async function createIsolatedDatabase(
  adminUrl: string,
  options: { owner?: string } = {},
): Promise<IsolatedDatabase> {
  const name = `it_${randomBytes(6).toString('hex')}`; // generated by us, so safe to place in SQL identifiers
  if (options.owner !== undefined && !/^[a-z_][a-z0-9_]*$/.test(options.owner))
    throw new Error('owner must be a simple role name');
  const admin = new PrismaClient({ datasourceUrl: adminUrl });
  await admin.$executeRawUnsafe(
    `CREATE DATABASE "${name}"${options.owner ? ` OWNER "${options.owner}"` : ''}`,
  );

  const url = withDatabase(adminUrl, name);

  const urlFor = (role: DatabaseRole): string => {
    if (role === 'admin') return url;
    const base = process.env[ROLE_ENV[role]];
    if (!base) throw new Error(`${ROLE_ENV[role]} is required (run "pnpm setup:env")`);
    return withDatabase(base, name);
  };

  return {
    name,
    url,
    urlFor,
    applyMigrations: () => deployMigrations(urlFor('migrate')),
    async drop() {
      try {
        await admin.$executeRawUnsafe(`DROP DATABASE IF EXISTS "${name}" WITH (FORCE)`);
      } finally {
        await admin.$disconnect();
      }
    },
  };
}

/** Runs the Prisma CLI's `migrate deploy` against one database. The URL goes in through the environment, never an argument. */
function deployMigrations(migrateUrl: string): Promise<void> {
  const apiRoot = resolve(__dirname, '../..');
  const prismaCli = createRequire(`${apiRoot}/package.json`).resolve('prisma/build/index.js');
  return new Promise((resolveRun, reject) => {
    execFile(
      process.execPath,
      [prismaCli, 'migrate', 'deploy'],
      {
        cwd: apiRoot,
        env: { ...process.env, DATABASE_MIGRATE_URL: migrateUrl },
        timeout: 120_000,
        windowsHide: true,
      },
      (error, _stdout, stderr) => {
        // The URL is only in the environment, but be careful anyway: report just the tail of the CLI's own message.
        if (error) reject(new Error(`prisma migrate deploy failed: ${String(stderr).slice(-600)}`));
        else resolveRun();
      },
    );
  });
}
